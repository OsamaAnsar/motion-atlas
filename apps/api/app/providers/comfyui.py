"""ComfyUI + Wan 2.2 provider (Milestones 8–11).

Talks to a local ComfyUI over HTTP (`/prompt`, `/history`, `/upload/image`,
`/interrupt`) and its WebSocket (`/ws`) for execution tracking. GPU metrics are
sampled from `nvidia-smi` in parallel during the run.

Not live-verified yet — exercise it only after a workflow has been generated by
hand in ComfyUI and exported to `comfy/workflows/` (see docs/comfyui-setup.md).
"""

from __future__ import annotations

import asyncio
import json
import time
import uuid
from pathlib import Path

import httpx
import websockets

from ..comfy import workflow_map as wf
from ..config import get_settings
from ..errors import (
    ComfyUIOfflineError,
    CudaOutOfMemoryError,
    WorkflowMissingError,
)
from ..logging import get_logger
from ..schemas import GpuSample, HealthState
from ..services import storage
from .base import RunContext, RunOutcome, VideoInferenceProvider

log = get_logger("comfyui")
settings = get_settings()

_OOM_MARKERS = ("out of memory", "cuda error", "outofmemoryerror", "alloc")


class ComfyUIProvider(VideoInferenceProvider):
    kind = "comfyui"

    def __init__(self) -> None:
        self._base = settings.comfyui_url.rstrip("/")
        self._ws_base = settings.comfyui_ws_url.rstrip("/")

    # ── health ────────────────────────────────────────────────────────────────

    async def health(self) -> tuple[HealthState, bool]:
        loaded = self._workflow_path("text-to-video").is_file()
        try:
            async with httpx.AsyncClient(timeout=2.0) as client:
                r = await client.get(f"{self._base}/system_stats")
            return (HealthState.online if r.status_code == 200 else HealthState.offline, loaded)
        except (httpx.HTTPError, OSError):
            return HealthState.offline, loaded

    # ── run ───────────────────────────────────────────────────────────────────

    async def run(self, ctx: RunContext) -> RunOutcome:
        row = ctx.row
        client_id = f"{settings.client_id}-{uuid.uuid4().hex[:8]}"

        ctx.emit({"type": "status", "jobId": row.job_id, "status": "preparing"})
        graph = self._template(ctx)

        if row.mode == "image-to-video" and row.image_name:
            await self._upload_image(row.image_name)

        prompt_id = await self._queue_prompt(graph, client_id)
        ctx.emit({"type": "status", "jobId": row.job_id, "status": "loading_model"})

        samples: list[GpuSample] = []
        stop_gpu = asyncio.Event()
        gpu_task = asyncio.create_task(self._sample_gpu(ctx, samples, stop_gpu))
        try:
            await self._track(ctx, client_id, prompt_id, graph)
        finally:
            stop_gpu.set()
            await gpu_task

        ctx.emit({"type": "status", "jobId": row.job_id, "status": "saving"})
        output_file = await self._collect_output(row.job_id, prompt_id)

        sampling_util = [s.utilization for s in samples if s.memory_used_mb > 6000]
        return RunOutcome(
            prompt_id=prompt_id,
            output_file=output_file,
            peak_vram_mb=max((s.memory_used_mb for s in samples), default=0) or None,
            average_gpu_utilization=(
                round(sum(sampling_util) / len(sampling_util)) if sampling_util else None
            ),
            gpu_samples=samples,
            timeline=[],
        )

    # ── steps ─────────────────────────────────────────────────────────────────

    def _workflow_path(self, mode: str) -> Path:
        name = "wan22_i2v.json" if mode == "image-to-video" else "wan22_t2v.json"
        return settings.workflows_dir / name

    def _template(self, ctx: RunContext) -> wf.Graph:
        row = ctx.row
        path = self._workflow_path(row.mode)
        if not path.is_file():
            raise WorkflowMissingError(
                f"{path.name} not found. Export it from ComfyUI (Save API Format)."
            )
        template: wf.Graph = json.loads(path.read_text("utf-8"))
        pos = row.prompt
        neg = row.negative_prompt or ""
        if row.mode == "image-to-video" and row.image_name:
            return wf.build_i2v(
                template, row, positive=pos, negative=neg, image_name=row.image_name
            )
        return wf.build_t2v(template, row, positive=pos, negative=neg)

    async def _queue_prompt(self, graph: wf.Graph, client_id: str) -> str:
        try:
            async with httpx.AsyncClient(timeout=15.0) as client:
                r = await client.post(
                    f"{self._base}/prompt", json={"prompt": graph, "client_id": client_id}
                )
        except (httpx.HTTPError, OSError) as exc:
            raise ComfyUIOfflineError(f"Could not reach ComfyUI at {self._base}: {exc}") from exc

        if r.status_code != 200:
            detail = r.text[:400]
            if any(m in detail.lower() for m in _OOM_MARKERS):
                raise CudaOutOfMemoryError("ComfyUI rejected the prompt: CUDA out of memory.")
            raise ComfyUIOfflineError(f"ComfyUI /prompt returned {r.status_code}: {detail}")
        data = r.json()
        if data.get("node_errors"):
            errors = json.dumps(data["node_errors"])[:400]
            raise ComfyUIOfflineError(f"Workflow node errors: {errors}")
        return str(data["prompt_id"])

    async def _upload_image(self, image_name: str) -> None:
        path = storage.upload_path(image_name)
        if path is None:
            raise ComfyUIOfflineError(f"Upload {image_name} missing on disk.")
        try:
            async with httpx.AsyncClient(timeout=30.0) as client:
                await client.post(
                    f"{self._base}/upload/image",
                    files={"image": (path.name, path.read_bytes())},
                    data={"overwrite": "true"},
                )
        except (httpx.HTTPError, OSError) as exc:
            raise ComfyUIOfflineError(f"Image upload to ComfyUI failed: {exc}") from exc

    async def _track(
        self, ctx: RunContext, client_id: str, prompt_id: str, graph: wf.Graph
    ) -> None:
        row = ctx.row
        url = f"{self._ws_base}/ws?clientId={client_id}"
        try:
            async with websockets.connect(url, max_size=8 * 1024 * 1024) as ws:
                while True:
                    if ctx.is_cancelled():
                        await self._interrupt()
                        return
                    try:
                        raw = await asyncio.wait_for(ws.recv(), timeout=180)
                    except TimeoutError as exc:
                        raise ComfyUIOfflineError("ComfyUI stopped sending updates.") from exc
                    if isinstance(raw, bytes):
                        continue  # preview image frames — ignored
                    msg = json.loads(raw)
                    mtype, data = msg.get("type"), msg.get("data", {})
                    if data.get("prompt_id") not in (None, prompt_id):
                        continue

                    if mtype == "execution_error":
                        text = json.dumps(data).lower()
                        if any(m in text for m in _OOM_MARKERS):
                            raise CudaOutOfMemoryError(
                                "CUDA out of memory during generation. Try a lower resolution "
                                "or fewer frames."
                            )
                        raise ComfyUIOfflineError(
                            f"ComfyUI execution error: {data.get('exception_message', 'unknown')}"
                        )
                    if mtype == "progress":
                        value, mx = data.get("value", 0), data.get("max", 1) or 1
                        ctx.emit({
                            "type": "progress",
                            "jobId": row.job_id,
                            "progress": round(value / mx, 4),
                            "step": value,
                            "totalSteps": mx,
                            "status": "sampling",
                        })
                    elif mtype == "executing":
                        node = data.get("node")
                        if node is None:
                            return  # this prompt finished
                        stage = wf.stage_for_node(graph, node)
                        ctx.emit({
                            "type": "status",
                            "jobId": row.job_id,
                            "status": stage or "sampling",
                        })
        except (websockets.WebSocketException, OSError) as exc:
            raise ComfyUIOfflineError(f"ComfyUI WebSocket dropped: {exc}") from exc

    async def _interrupt(self) -> None:
        try:
            async with httpx.AsyncClient(timeout=5.0) as client:
                await client.post(f"{self._base}/interrupt")
        except (httpx.HTTPError, OSError):
            log.warning("interrupt request failed")

    async def _collect_output(self, job_id: str, prompt_id: str) -> str | None:
        async with httpx.AsyncClient(timeout=15.0) as client:
            for _ in range(20):
                r = await client.get(f"{self._base}/history/{prompt_id}")
                entry = r.json().get(prompt_id) if r.status_code == 200 else None
                if entry:
                    found = wf.find_output_file(entry)
                    if found:
                        return await self._fetch_video(client, job_id, found)
                await asyncio.sleep(0.5)
        log.warning("no output file in history", extra={"prompt_id": prompt_id})
        return None

    async def _fetch_video(
        self, client: httpx.AsyncClient, job_id: str, found: dict[str, str]
    ) -> str:
        dest = storage.generation_video_path(job_id)
        if settings.comfyui_output_dir:
            src = Path(settings.comfyui_output_dir) / found["subfolder"] / found["filename"]
            if src.is_file():
                storage.store_generation_video(job_id, src)
                return dest.name
        r = await client.get(
            f"{self._base}/view",
            params={
                "filename": found["filename"],
                "subfolder": found["subfolder"],
                "type": found["type"],
            },
        )
        r.raise_for_status()
        dest.write_bytes(r.content)
        return dest.name

    async def _sample_gpu(
        self, ctx: RunContext, sink: list[GpuSample], stop: asyncio.Event
    ) -> None:
        while not stop.is_set():
            m = await ctx.gpu.read(force=True)
            if m.available:
                sink.append(
                    GpuSample(
                        t=int(time.time() * 1000),
                        utilization=m.utilization,
                        memory_used_mb=m.memory_used_mb,
                        temperature=m.temperature,
                        power_watts=m.power_watts,
                    )
                )
                ctx.emit({"type": "gpu_metrics", "jobId": ctx.row.job_id,
                          "metrics": m.model_dump(by_alias=True)})
                if len(sink) > 240:
                    sink.pop(0)
            try:
                await asyncio.wait_for(stop.wait(), timeout=2.0)
            except TimeoutError:
                pass
